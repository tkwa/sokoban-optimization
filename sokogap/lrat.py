"""Data-only ASCII LRAT checker: ordered RUP, RAT, and clause deletion.

The input formula is generated by the trusted Sokoban encoder. A solver is
never part of the trusted checker. Clause IDs start at one in DIMACS order.
"""

from array import array
from io import StringIO

from .budget import Exhausted, spend
from .core import Invalid

MAX_PROOF_BYTES = 48 * 1024**2
MAX_STEPS = 1_000_000
MAX_LINE_BYTES = 4 * 1024**2
MAX_ID = 2**31 - 1
MAX_VARIABLE = 4_000_000


def check_lrat(cnf, proof: str) -> dict:
    if not isinstance(proof, str) or not proof.isascii():
        raise Invalid("LRAT proof must be ASCII text")
    if len(proof) > MAX_PROOF_BYTES:
        raise Exhausted("LRAT proof size limit exceeded")
    original = len(cnf)
    added, deleted = {}, set()
    last = original
    occurrences = None
    steps = 0
    finished = False

    def clause(cid):
        if not 0 < cid <= MAX_ID or cid in deleted:
            raise Invalid("LRAT hint refers to an inactive clause")
        if cid <= original:
            return cnf[cid - 1]
        if cid not in added:
            raise Invalid("LRAT hint refers to an unknown clause")
        return added[cid]

    def assume(assignment, literals):
        for lit in literals:
            spend("lrat_literals")
            var, value = abs(lit), lit > 0
            if var in assignment and assignment[var] != value:
                return True
            assignment[var] = value
        return False

    def propagate(assignment, hints):
        for cid in hints:
            if cid <= 0:
                raise Invalid("expected a positive LRAT propagation hint")
            row = clause(cid)
            spend("lrat_literals", len(row) + 1)
            unassigned = set()
            satisfied = False
            for lit in row:
                value = assignment.get(abs(lit))
                if value is None:
                    unassigned.add(lit)
                elif value == (lit > 0):
                    satisfied = True
                    break
            if satisfied:
                continue
            if not unassigned:
                return True
            if len(unassigned) != 1:
                raise Invalid("LRAT hint is neither unit nor conflicting")
            lit = next(iter(unassigned))
            assignment[abs(lit)] = lit > 0
        return False

    def occurrence_index():
        nonlocal occurrences
        if occurrences is None:
            occurrences = {}
            for cid in range(1, original + 1):
                if cid not in deleted:
                    row = cnf[cid - 1]
                    spend("lrat_literals", len(row) + 1)
                    for lit in set(row):
                        occurrences.setdefault(lit, array("I")).append(cid)
            for cid, row in added.items():
                for lit in set(row):
                    occurrences.setdefault(lit, array("I")).append(cid)
        return occurrences

    for line in StringIO(proof):
        if len(line) > MAX_LINE_BYTES:
            raise Exhausted("LRAT line size limit exceeded")
        line = line.strip()
        if not line or line.startswith("c"):
            continue
        if finished:
            raise Invalid("LRAT statements follow the empty clause")
        steps += 1
        if steps > MAX_STEPS:
            raise Exhausted("LRAT step limit exceeded")
        parts = line.split()
        deletion = len(parts) > 1 and parts[1] == "d"
        tokens = parts[:1] + parts[2:] if deletion else parts
        if any(len(t.lstrip("-")) > 10 or not t.lstrip("-").isdigit() or t.startswith("--") for t in tokens):
            raise Invalid("invalid LRAT integer")
        values = list(map(int, tokens))
        if not values or not 0 < values[0] <= MAX_ID or any(abs(v) > MAX_ID for v in values):
            raise Invalid("LRAT integer outside supported range")
        spend("lrat_literals", len(values))
        if deletion:
            if values[-1] != 0 or any(v <= 0 for v in values[1:-1]):
                raise Invalid("invalid LRAT deletion")
            for cid in values[1:-1]:
                clause(cid)
                deleted.add(cid)
                added.pop(cid, None)
            continue
        cid, *body = values
        if cid <= last or body.count(0) != 2 or not body or body[-1] != 0:
            raise Invalid("LRAT additions need increasing fresh IDs and two terminators")
        split = body.index(0)
        row = tuple(dict.fromkeys(body[:split]))
        hints = body[split + 1:-1]
        if any(abs(lit) > MAX_VARIABLE for lit in row):
            raise Exhausted("LRAT variable limit exceeded")
        assignment = {}
        conflict = assume(assignment, (-lit for lit in row))
        first_rat = next((i for i, hint in enumerate(hints) if hint < 0), len(hints))
        if not conflict:
            conflict = propagate(assignment, hints[:first_rat])
        if not conflict:
            if not row:
                raise Invalid("empty LRAT clause lacks a RUP contradiction")
            pivot = row[0]
            index = occurrence_index()
            required = {other for other in index.get(-pivot, ()) if other not in deleted}
            seen = set()
            position = first_rat
            while position < len(hints):
                other = -hints[position]
                if other <= 0 or other in seen or other not in required:
                    raise Invalid("invalid or repeated LRAT RAT clause")
                seen.add(other)
                end = position + 1
                while end < len(hints) and hints[end] > 0:
                    end += 1
                trial = assignment.copy()
                # C union (D minus -pivot), retaining C's pivot, is the AT
                # check needed for RAT and permits the shared RUP prefix.
                conflict_other = assume(trial, (-lit for lit in clause(other) if lit != -pivot))
                if not conflict_other:
                    conflict_other = propagate(trial, hints[position + 1:end])
                if not conflict_other:
                    raise Invalid("LRAT RAT block lacks a contradiction")
                position = end
            if seen != required:
                raise Invalid("LRAT RAT proof omits an active opposite-pivot clause")
        last = cid
        added[cid] = row
        if occurrences is not None:
            for lit in row:
                occurrences.setdefault(lit, array("I")).append(cid)
        if not row:
            finished = True
    if not finished:
        raise Invalid("LRAT proof does not derive the empty clause")
    return {"steps": steps, "last_clause_id": last}


def verify_sat_lower(board, certificate):
    from .sat import ENCODING, encode_push_bound
    from .scoring import integer
    expected = {"format", "board_sha256", "encoding", "lower", "cnf_sha256", "proof"}
    if set(certificate) != expected or certificate["format"] != "sokogap-sat-lrat-v1":
        raise Invalid("invalid SAT lower-bound certificate fields")
    if certificate["board_sha256"] != board.digest or certificate["encoding"] != ENCODING:
        raise Invalid("SAT certificate board or encoding differs")
    lower = integer(certificate["lower"], "SAT lower bound")
    if lower < 1:
        raise Invalid("SAT certificate lower bound must be positive")
    cnf = encode_push_bound(board, lower - 1)
    if certificate["cnf_sha256"] != cnf.digest:
        raise Invalid("SAT formula hash differs from the regenerated formula")
    check_lrat(cnf, certificate["proof"])
    return lower + ((board.push_parity - lower) % 2)
